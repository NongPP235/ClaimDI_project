// Each role receives the list with statuses for every case, and the full
// case content only where it does that case's work.
export async function snapshotFor(s: Session, role: UserRole) {
  const full = (await snapshot(s)) as Snapshot;
  const detailIds = new Set<string>();
  const cases = full.cases.map((c) => {
    if (seesCaseDetail(role, c.status)) {
      detailIds.add(c.id);
      return { ...c, detail: true };
    }
    const sc = c.scenario;
    return {
      ...c,
      proposal: "",
      detail: false,
      scenario: {
        code: sc.code,
        title: sc.title,
        department: sc.department,
        payer: sc.payer,
        amount: sc.amount,
        status: sc.status,
      },
      audit:
        role === "engineer" && c.audit
          ? { rule_version: (c.audit as { rule_version: string }).rule_version }
          : null,
    };
  });
  const history = full.history.filter((h) =>
    h.case_id
      ? detailIds.has(h.case_id)
      : role === "admin" || role === "engineer",
  );
  return { ...full, cases, history };
}
export const exportFormats = ["print", "csv", "json"];
const exportLabels: Record<string, string> = {
  print: "พิมพ์ / PDF",
  csv: "Excel (CSV)",
  json: "JSON",
};
export async function mutate(
  s: Session,
  input: {
    action: string;
    id?: string;
    revision?: number;
    note?: string;
    version?: string;
    ids?: string[];
    format?: string;
    package?: string;
    window?: string;
    rate?: number;
  },
  actor?: Actor,
): Promise<{ simulatedError?: boolean } | undefined> {
  await db();
  // Logged-in actions record who did them; tests and the anonymous demo
  // fall back to the role that normally owns the step.
  const by = (role: UserRole) => actor?.role ?? role,
    name = actor?.name ?? "";
  return transaction(async () => {
    if (input.action === "reset") {
      await run("DELETE FROM review_history WHERE session_id=?", s.id);
      await run("DELETE FROM cases WHERE session_id=?", s.id);
      await run(
        "UPDATE demo_sessions SET active_rule_version='1.0' WHERE id=?",
        s.id,
      );
      await seed(s.id);
      return;
    }
    if (input.action === "rule") {
      if (!["1.0", "2.0"].includes(input.version || ""))
        throw new AppError("เวอร์ชันไม่ถูกต้อง");
      if (s.active_rule_version === input.version) return;
      await run(
        "UPDATE demo_sessions SET active_rule_version=? WHERE id=?",
        input.version!,
        s.id,
      );
      await record(
        s.id,
        null,
        "เปลี่ยนกฎจำลอง",
        `${s.active_rule_version} → ${input.version}`,
        by("engineer"),
        null,
        name,
      );
      return;
    }
    if (input.action === "package") {
      const pkg = input.package ?? "";
      if (!packageNames.includes(pkg)) throw new AppError("แพ็กเกจไม่ถูกต้อง");
      if (s.package === pkg) return;
      await run("UPDATE demo_sessions SET package=? WHERE id=?", pkg, s.id);
      await record(
        s.id,
        null,
        "เปลี่ยนแพ็กเกจ",
        `${s.package ?? "Plus"} → ${pkg}`,
        by("admin"),
        null,
        name,
      );
      return;
    }
    if (input.action === "denial_rate") {
      const rate = input.rate;
      if (!Number.isInteger(rate) || rate! < 0 || rate! > 100)
        throw new AppError("อัตราการถูกปฏิเสธต้องเป็นจำนวนเต็ม 0–100%");
      if (s.denial_rate === rate) return;
      await run(
        "UPDATE demo_sessions SET denial_rate=? WHERE id=?",
        rate!,
        s.id,
      );
      await record(
        s.id,
        null,
        "เปลี่ยนอัตราการถูกปฏิเสธที่สมมติ",
        `${s.denial_rate ?? 30}% → ${rate}%`,
        by("cfo"),
        null,
        name,
      );
      return;
    }
    if (input.action === "drift") {
      const window = driftWindows.find((w) => w.key === input.window);
      if (!window) throw new AppError("เลือกช่วงข้อมูลที่จะตรวจ");
      await record(
        s.id,
        null,
        "ตรวจ Data Drift",
        driftNote(window.key),
        by("engineer"),
        null,
        name,
      );
      return;
    }
    if (input.action === "export") {
      // Export only records who took which ready cases out and in what
      // format; the file itself is built from data this role already sees.
      const ids = [...new Set(input.ids ?? [])];
      if (!exportFormats.includes(input.format ?? "") || !ids.length)
        throw new AppError("เลือกเคสและรูปแบบไฟล์ก่อนส่งออก");
      for (const id of ids) {
        const c = await owned(s.id, id);
        if (c.status !== "ready")
          throw new AppError("ส่งออกได้เฉพาะเคสที่พร้อมส่งเคลม", 409);
        await record(
          s.id,
          c.id,
          "ส่งออกข้อมูลเคลม",
          exportLabels[input.format!],
          actor?.role ?? "coder",
          c.revision,
          name,
        );
      }
      return;
    }
    const c = await owned(s.id, input.id || "");
    if (c.revision !== input.revision)
      throw new AppError(
        "เคสนี้มีข้อมูลใหม่ โหลดข้อมูลล่าสุดก่อนดำเนินการต่อ",
        409,
      );
    const scenario = scenarioOf(c);
    let status = c.status,
      proposal = c.proposal;
    const revision = c.revision + 1;
    if (input.action === "analyze") {
      if (c.status === "awaiting_review")
        throw new AppError("เคสอยู่ระหว่างรอแพทย์ตรวจทาน", 409);
      if (c.scenario_key === 5 && c.attempts === 0) {
        await run("UPDATE cases SET attempts=1 WHERE id=?", c.id);
        return { simulatedError: true };
      }
      status = "needs_revision";
      proposal = "";
      await insertAudit(
        c.id,
        revision,
        findingsFor(scenario, s.active_rule_version),
        s.active_rule_version,
        new Date().toISOString(),
      );
      await record(
        s.id,
        c.id,
        "ตรวจตัวอย่าง",
        `กฎ ${s.active_rule_version}`,
        by("coder"),
        revision,
        name,
      );
    } else if (input.action === "proposal") {
      if (!["needs_revision", "returned"].includes(c.status))
        throw new AppError("ตรวจเคสก่อนสร้างข้อเสนอ", 409);
      proposal = scenario.proposal;
      await record(
        s.id,
        c.id,
        "สร้างข้อเสนอแก้ไข",
        "",
        by("coder"),
        revision,
        name,
      );
    } else if (input.action === "submit") {
      if (!["needs_revision", "returned"].includes(c.status) || !c.proposal)
        throw new AppError("สร้างข้อเสนอก่อนส่งให้แพทย์", 409);
      status = "awaiting_review";
      await record(
        s.id,
        c.id,
        "ส่งให้แพทย์ตรวจทาน",
        "",
        by("coder"),
        revision,
        name,
      );
    } else if (input.action === "approve") {
      if (c.status !== "awaiting_review")
        throw new AppError("เคสนี้ไม่ได้รอแพทย์", 409);
      status = "ready";
      await record(
        s.id,
        c.id,
        "แพทย์ยืนยันข้อเสนอ",
        "",
        by("doctor"),
        revision,
        name,
      );
    } else if (input.action === "return") {
      if (c.status !== "awaiting_review")
        throw new AppError("เคสนี้ไม่ได้รอแพทย์", 409);
      const note = input.note?.trim();
      if (!note || note.length > 500)
        throw new AppError("ระบุเหตุผล 1–500 ตัวอักษร");
      status = "returned";
      proposal = "";
      await record(
        s.id,
        c.id,
        "แพทย์ส่งกลับ",
        note,
        by("doctor"),
        revision,
        name,
      );
    } else throw new AppError("การกระทำไม่ถูกต้อง");
    await run(
      "UPDATE cases SET status=?,proposal=?,revision=?,updated_at=? WHERE id=?",
      status,
      proposal,
      revision,
      new Date().toISOString(),
      c.id,
    );
  });
}

// Import from HIS (PROJECT_PLAN.md §19). Preview and import parse the same
// files; import skips cases whose code is already in the workspace.
export async function hisImport(
  s: Session,
  files: HisInput,
  commit: boolean,
  actor?: Actor,
) {
  await db();
  const result = buildCases(files);
  const codes = async () =>
    new Set(
      (
        await all<{ scenario_json: string }>(
          "SELECT scenario_json FROM cases WHERE session_id=? AND source='his'",
          s.id,
        )
      ).map((r) => (JSON.parse(r.scenario_json) as Scenario).code),
    );
  const existing = await codes();
  const cases = result.cases.map((c) => ({
    ...c,
    duplicate: existing.has(c.code),
  }));
  if (!commit || result.errors.length) return { ...result, cases, imported: 0 };
  const fresh = cases.filter((c) => !c.duplicate);
  if (!fresh.length) throw new AppError("ทุกเคสในไฟล์นำเข้าไว้แล้ว", 409);
  const imported = await transaction(async () => {
    // Check again under the lock, in case another import just finished.
    const now = new Date().toISOString(),
      seen = await codes();
    let n = 0;
    for (const c of fresh) {
      if (seen.has(c.code)) continue;
      const id = randomUUID();
      const { key: _key, visit: _visit, duplicate: _dup, ...scenario } = c;
      await run(
        "INSERT INTO cases(id,session_id,scenario_key,status,revision,proposal,attempts,updated_at,scenario_json,source) VALUES(?,?,-1,'draft',0,'',0,?,?,'his')",
        id,
        s.id,
        now,
        JSON.stringify(scenario),
      );
      await record(
        s.id,
        id,
        "นำเข้าจาก HIS",
        `แฟ้ม ${result.files.join(", ")}`,
        actor?.role ?? "coder",
        0,
        actor?.name ?? "",
      );
      n++;
    }
    if (!n) throw new AppError("ทุกเคสในไฟล์นำเข้าไว้แล้ว", 409);
    return n;
  });
  return { ...result, cases, imported };
}
