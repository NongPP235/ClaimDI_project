async function migrate() {
  await transaction(async () => {
    await exec(
      "CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY); ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY;",
    );
    const done = new Set(
      (
        await all<{ version: number }>("SELECT version FROM schema_migrations")
      ).map((r) => r.version),
    );
    for (const [version, sql] of migrations) {
      if (done.has(version)) continue;
      try {
        await exec(sql);
      } catch (e) {
        throw new Error(`migration ${version} failed: ${(e as Error).message}`);
      }
      await run("INSERT INTO schema_migrations VALUES(?)", version);
    }
  });
}
// Migrations are checked once per module load, so a `next dev` reload that
// brings a new migration still applies it to the open connection.
let ready: Promise<void> | undefined;
export async function db() {
  ready ??= migrate().catch((e) => {
    ready = undefined;
    throw e;
  });
  await ready;
}
export const schemaVersions = () =>
  db().then(() =>
    all<{ version: number }>(
      "SELECT version FROM schema_migrations ORDER BY version",
    ).then((r) => r.map((x) => x.version)),
  );
